export const CHANNEL_IDS: ChannelId[] = ["direct", "booking", "expedia", "agoda", "airbnb"];

const AGODA_DOTS = ["#e4312b", "#f7941d", "#f9c013", "#6cb33f", "#2b6cb5"];

// A channel's logo as a small rounded tile.
export function ChannelLogo({ id, size = 18 }: { id: ChannelId; size?: number }) {
  const box = (bg: string, child: ReactNode, extra = "") => (
    <span aria-hidden="true" className={`inline-flex flex-none items-center justify-center overflow-hidden ${extra}`} style={{ width: size, height: size, borderRadius: size * 0.24, background: bg }}>
      {child}
    </span>
  );
  const svg = (d: string, fill: string, scale = 1) => (
    <svg viewBox="0 0 24 24" width={size * scale} height={size * scale} fill={fill}>
      <path d={d} />
    </svg>
  );
  switch (id) {
    case "booking":
      return box("#ffffff", svg(PATHS.booking, "#003a9a"));
    case "expedia":
      return box("#191e3b", svg(PATHS.expedia, "#fddb32"));
    case "airbnb":
      return box("#ff5a5f", svg(PATHS.airbnb, "#ffffff", 0.66));
    case "agoda":
      return box(
        "#ffffff",
        <svg viewBox="0 0 24 24" width={size} height={size}>
          <text x="12" y="13.2" textAnchor="middle" fontSize="13.5" fontWeight="700" fill="#2a2a2a" fontFamily="var(--font-manrope), sans-serif">
            a
          </text>
          {AGODA_DOTS.map((c, i) => (
            <circle key={c} cx={4.4 + i * 3.8} cy={18.6} r={1.55} fill={c} />
          ))}
        </svg>,
        "ring-1 ring-inset ring-black/10",
      );
    default:
      return box("#c79a45", <Globe size={size * 0.62} color="#221b16" strokeWidth={2.4} />);
  }
}

// A channel's logo and name, tinted in its colours.
export function ChannelChip({ id, label, className = "" }: { id: ChannelId; label?: string; className?: string }) {
  const c = CHANNEL[id];
  return (
    <span className={`inline-flex items-center gap-1.5 whitespace-nowrap rounded py-0.5 pl-0.5 pr-2 text-[11px] font-semibold ${className}`} style={{ background: c.tint, color: c.ink }}>
      <ChannelLogo id={id} size={15} />
      {label ?? c.name}
    </span>
  );
}

